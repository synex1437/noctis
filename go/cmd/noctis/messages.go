var (
	baseOnce     sync.Once
	baseCache    map[string]map[string]string
	catalogCache = map[string]map[string]string{}
)

func baseTable() map[string]map[string]string {
	baseOnce.Do(func() { baseCache = baseCatalog() })
	return baseCache
}

// baseLocales names the catalogs baseCatalog builds, so knownLocale answers without building them.
var baseLocales = map[string]bool{"en": true, "tr": true}

func knownLocale(code string) bool {
	if code == "" {
		return false
	}
	if _, ok := extraCatalogBuilders[code]; ok {
		return true
	}
	return baseLocales[code]
}

func catalogFor(code string) map[string]string {
	if table, seen := catalogCache[code]; seen {
		return table
	}
	table := baseTable()[code]
	if table == nil {
		if build, ok := extraCatalogBuilders[code]; ok {
			table = build()
		}
	}
	catalogCache[code] = table
	return table
}

func detectLocale(cfg object) string {
	candidates := []string{os.Getenv("NOCTIS_LANG"), getString(cfg, "locale")}
	for _, candidate := range candidates {
		code := strings.ToLower(strings.TrimSpace(candidate))
		if knownLocale(code) {
			return code
		}
	}
	for _, variable := range []string{"LC_ALL", "LC_MESSAGES", "LANG"} {
		value := strings.ToLower(os.Getenv(variable))
		if len(value) >= 2 && knownLocale(value[:2]) {
			return value[:2]
		}
		if value != "" && value != "c" && value != "posix" {
			break
		}
	}
	return "en"
}

func setLocale(cfg object) {
	locale = detectLocale(cfg)
}

var (
	localeLock    sync.Mutex
	localePending func()
)

// settleLocaleLater has the locale finished by settle the first time text is looked up, so a hook
// that prints nothing never reads what settle needs. nil drops a pending settle.
func settleLocaleLater(settle func()) {
	localeLock.Lock()
	defer localeLock.Unlock()
	localePending = settle
}

func localeNow() string {
	localeLock.Lock()
	defer localeLock.Unlock()
	if settle := localePending; settle != nil {
		localePending = nil
		settle()
	}
	return locale
}

func T(key string, values ...any) string {
	text, ok := catalogFor(localeNow())[key]
	if !ok {
		text, ok = catalogFor("en")[key]
	}
	if !ok {
		return key
	}
	if len(values) == 0 {
		return copiedSkillCommands(text)
	}
	return copiedSkillCommands(fmt.Sprintf(text, values...))
}

func dayName(weekday int) string {
	names := dayNamesByLocale[localeNow()]
	if names == nil {
		names = dayNamesByLocale["en"]
	}
	return names[weekday%7]
}

func durationUnit(index int) string {
	units, ok := durationUnits[localeNow()]
	if !ok {
		units = durationUnits["en"]
	}
	return units[index]
}
